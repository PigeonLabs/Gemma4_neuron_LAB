def figure(s):
    import matplotlib
    matplotlib.use('Agg')
    matplotlib.rcParams['svg.hashsalt']='round6_task_readiness'
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    titles=['A: original numeric route task','A2: explicit route task','B: truth vs. substitute source','C: reusable intermediate']
    fig,axes=plt.subplots(2,2,figsize=(14,9));fig.subplots_adjust(left=.15,right=.95,bottom=.13,top=.86,wspace=.65,hspace=.55)
    fig.suptitle('R6 discovery task readiness',x=.06,ha='left',fontsize=21,fontweight='bold',y=.98)
    fig.text(.06,.925,'Four registered runs; all stopped before scientific native-coordinate discovery.',fontsize=11,color='#374151')
    data=[]
    for ax,r,title in zip(axes.flat,s['studies'],titles):
        names=list(r['readiness']);n=len(names);ax.set_title(title,loc='left',fontsize=12,pad=12,fontweight='bold')
        for i,name in enumerate(names):
            v=r['readiness'][name];threshold=95 if name=='code_only' else 85;value=100*v['accuracy'];passed=value>=threshold
            ax.barh(i,value,height=.60,color='#315b8a' if passed else '#c18428',zorder=2)
            ax.vlines(threshold,i-.38,i+.38,color='#111827',linewidth=1.5,zorder=3)
            ax.text(103,i,f"{value:.1f}% ({v['correct']}/{v['n']})",va='center',fontsize=9,color='#111827')
            data.append({'stage':r['stage'],'condition':name,'correct':v['correct'],'rows':v['n'],'episodes':v['episodes'],'accuracy':v['accuracy'],'threshold':threshold/100.})
        ax.set_yticks(range(n),[LABELS[k] for k in names],fontsize=10);ax.set_ylim(5.6,-.6);ax.set_xlim(0,145)
        ax.set_xticks([0,25,50,75,100],['0%','25%','50%','75%','100%']);ax.set_axisbelow(True);ax.grid(axis='x',color='#e5e7eb',linewidth=.7)
        for side in ('top','right'):ax.spines[side].set_visible(False)
        ax.spines['left'].set_color('#d1d5db');ax.spines['bottom'].set_color('#d1d5db')
    fig.text(.06,.066,'Bar labels: correct / rows. Each run uses 8 independent worlds; rows include repeated queries and codebooks.',fontsize=10,color='#374151')
    fig.text(.06,.04,'Black ticks: registered threshold (task 85%, code 95%). Discovery observations; no confirmation estimates.',fontsize=10,color='#374151')
    fig.legend(handles=[Line2D([0],[0],color='#315b8a',lw=7,label='Condition passes'),Line2D([0],[0],color='#c18428',lw=7,label='Condition fails')],loc='upper right',bbox_to_anchor=(.95,.982),frameon=False,ncol=2)
    svg=ROOT/'figures/round6_task_readiness.svg';fig.savefig(svg,metadata={'Date':None});fig.savefig(ROOT/'runs/round6_task_readiness.png',dpi=140);plt.close(fig)
    svg.write_text('\n'.join(line.rstrip() for line in svg.read_text().splitlines())+'\n')
    metadata={'source':'logs/summary/round6_execution_results.json','source_sha256':sha(DEST),'unit':'restricted next-token accuracy','uncertainty':'descriptive discovery observations; no inference between repeated rows or studies','rows':data,'svg_sha256':sha(svg),'generator':'scripts/build_round6_execution_report.py'}
    (ROOT/'figures/round6_task_readiness_metadata.json').write_text(dump(metadata))


def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args();s=result();text=dump(s);report_text=report(s);rp=ROOT/'reports/ROUND6_EXECUTION_RESULTS_KO.md'
    if a.check:
        assert DEST.read_text()==text and rp.read_text()==report_text
        m=load(ROOT/'figures/round6_task_readiness_metadata.json');assert m['source_sha256']==sha(DEST) and m['svg_sha256']==sha(ROOT/'figures/round6_task_readiness.svg')
        print('PASS: R6 result JSON, report and figure provenance match verified measurements')
    else:
        DEST.write_text(text);rp.write_text(report_text);figure(s);print('Built R6 execution result JSON, report and figure')


if __name__=='__main__':main()
