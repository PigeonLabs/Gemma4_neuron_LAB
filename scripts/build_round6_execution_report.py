#!/usr/bin/env python3
"""Build R6 execution status, report and scientific figure from verified JSON."""
from __future__ import annotations
import argparse,hashlib,json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
NAMES={'round6_A_discovery':'A: 원래 숫자 선택자 과제','round6x_A_discovery':'A2: 명시적 경로 과제','round6x_B_discovery':'B: 손상 후 진실·출처 백업','round6x_C_discovery':'C: 재사용 가능한 중간값'}
LABELS={'conflict_direct':'Conflict / direct','conflict_compose':'Conflict / composition','direct_only':'Direct only','composition_only':'Composition only','code_only':'Code only','agreement':'Dual / agreement','conflict1':'Dual / conflict 1','conflict2':'Dual / conflict 2','composition':'Composition'}
DEST=ROOT/'logs/summary/round6_execution_results.json'


def load(p):return json.loads(p.read_text())
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def dump(v):return json.dumps(v,indent=2,ensure_ascii=False,allow_nan=False)+'\n'


def result():
    replay=load(ROOT/'logs/summary/round6_execution_replay.json');assert replay['status']=='PASS' and len(replay['records'])==4
    studies=[]
    for rr in replay['records']:
        stage=rr['stage'];path=ROOT/f'logs/summary/{stage}.json';s=load(path)
        assert sha(path)==rr['summary_sha256'] and s['actual_forward_calls']==rr['scientific_calls']
        meta=load(ROOT/'runs'/s['run_id']/'metadata.json');tech=load(ROOT/f'logs/summary/{stage}_technical.json')
        studies.append({'stage':stage,'title_ko':NAMES[stage],'study_id':meta['config']['studies'][s['study']]['id'],
            'run_id':s['run_id'],'execution_status':s['status'],'technical_status':tech['status'],'gate':s['outcome']['gate'],
            'scientific_conclusion':'NOT_IDENTIFIABLE','scientific_forward_calls':rr['scientific_calls'],'technical_forward_calls':rr['technical_calls'],
            'total_actual_forwards':rr['total_actual_forwards'],'readiness':rr['readiness'],
            'readiness_episode_count':8,'registered_discovery_episodes':12,'calibration':'NOT_EVALUATED','confirmation':'NOT_EVALUATED',
            'native_candidate_search':'NOT_EVALUATED' if s['outcome']['gate']=='STOPPED_AT_TASK_READINESS' else 'SEE_DISCOVERY_SUMMARY',
            'elapsed_scientific_seconds':s['elapsed_seconds'],'elapsed_technical_seconds':tech['elapsed_seconds'],
            'peak_GPU_reserved_bytes':max(s['peak_reserved_bytes'],tech['peak_reserved_bytes']),
            'peak_CPU_RSS_bytes':s['peak_CPU_RSS_bytes'],'started_kst':meta['started_kst'],'ended_kst':meta['ended_kst'],
            'measurement_seed':s['measurement_seed'],'loading_seed':s['loading_seed'],'corpus_seed':s['corpus_seed'],
            'summary_path':str(path.relative_to(ROOT)),'summary_sha256':sha(path),'raw_rows_sha256':rr['rows_sha256'],
            'registration_sha256':rr['registration_sha256'],'environment':meta['environment']})
    assert all(r['gate']=='STOPPED_AT_TASK_READINESS' for r in studies),'New outcomes require a reviewed extension of this stopped-study report'
    total=sum(r['total_actual_forwards'] for r in studies);assert total==replay['total_actual_forwards']==744
    return {'schema_version':1,'date_kst':'2026-10-30','status':'EXECUTED_AND_STOPPED_AT_REGISTERED_PREREQUISITES',
        'model_id':'google/gemma-4-12B-it','model_revision':'707f0a3b8a3c7ad586ed01e27eafbad8a27dd0f7',
        'scientific_dtype':'FP32 upcast of the same stored BF16 parameter values','technical_dtypes':['BF16','FP32'],
        'requested_studies':['A','B','C'],'additional_separately_registered_revision':'A2; one revision only',
        'total_actual_forwards':total,'scientific_forward_calls':sum(r['scientific_forward_calls'] for r in studies),
        'technical_forward_calls':sum(r['technical_forward_calls'] for r in studies),'budget_forward_cap':52000,
        'behavior_measure':'restricted A/B/C/D next-token argmax; full-vocabulary top1 separately audited',
        'task_accuracy_threshold':.85,'code_accuracy_threshold':.95,
        'calibration_confirmation_model_calls':0,'scientific_conclusion':'NOT_IDENTIFIABLE',
        'causal_bottleneck':'NOT_EVALUATED','backup_recruitment':'NOT_EVALUATED','reusable_intermediate':'NOT_EVALUATED',
        'original_and_revision_are_separate_studies':True,'historical_R2_R3_R5_R6_review_files_preserved':True,
        'replay_path':'logs/summary/round6_execution_replay.json','replay_sha256':sha(ROOT/'logs/summary/round6_execution_replay.json'),
        'studies':studies}


